package cmd

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestWriteTeamsAppPackOutput_PreservesUnownedPackage(t *testing.T) {
	dir := t.TempDir()
	outputPath := filepath.Join(dir, teamsAppPackageFile)
	if err := os.WriteFile(outputPath, []byte("USER-CUSTOMIZED"), 0o600); err != nil {
		t.Fatal(err)
	}

	err := writeTeamsAppPackOutput(outputPath, []byte("AZD-GENERATED"))
	if err == nil {
		t.Fatal("expected existing unowned package error")
	}
	if !strings.Contains(err.Error(), "already exists and was not generated by azd") {
		t.Fatalf("unexpected error: %v", err)
	}
	data, _ := os.ReadFile(outputPath)
	if string(data) != "USER-CUSTOMIZED" {
		t.Errorf("unowned package was overwritten; content = %q", string(data))
	}
}

func TestWriteTeamsAppPackOutput_OverwritesOwnedPackage(t *testing.T) {
	dir := t.TempDir()
	outputPath := filepath.Join(dir, teamsAppPackageFile)
	markerPath := filepath.Join(dir, teamsAppPackageMarkerFile)
	if err := os.WriteFile(outputPath, []byte("OLD"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(markerPath, []byte(teamsAppPackageMarkerContent([]byte("OLD"))), 0o600); err != nil {
		t.Fatal(err)
	}

	if err := writeTeamsAppPackOutput(outputPath, []byte("NEW")); err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	data, _ := os.ReadFile(outputPath)
	if string(data) != "NEW" {
		t.Errorf("owned package should be overwritten; content = %q", string(data))
	}
	if !teamsAppPackageIsOwned(outputPath, markerPath) {
		t.Errorf("marker must be updated for the new package")
	}
}
