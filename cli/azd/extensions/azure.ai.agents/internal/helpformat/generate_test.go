// cspell:ignore helpformat
package helpformat

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

func TestGeneratedExtensionFormatters(t *testing.T) {
	source, err := os.ReadFile("helpformat.go")
	require.NoError(t, err)
	manifests, err := filepath.Glob(filepath.Join("..", "..", "..", "*", "extension.yaml"))
	require.NoError(t, err)
	require.NotEmpty(t, manifests)
	count := 0
	for _, manifest := range manifests {
		root := filepath.Dir(manifest)
		data, err := os.ReadFile(manifest)
		require.NoError(t, err)
		if !strings.Contains(string(data), "\nnamespace: ai.") || filepath.Base(root) == "azure.ai.agents" {
			continue
		}
		count++
		t.Run(filepath.Base(root), func(t *testing.T) {
			generated, err := os.ReadFile(filepath.Join(root, "internal", "helpformat", "helpformat.go"))
			require.NoError(t, err, "run go generate ./internal/helpformat from azure.ai.agents")
			require.Equal(t,
				strings.Replace(strings.Replace(string(source), "//go:generate go run ./internal/generate\n\n", "", 1),
					"\n\n", "\n\n// Code generated by go generate ./internal/helpformat from azure.ai.agents; DO NOT EDIT.\n\n", 1),
				string(generated), "run go generate ./internal/helpformat from azure.ai.agents")
		})
	}
	require.Equal(t, 13, count, "update the inventory when adding an AI extension")
}
