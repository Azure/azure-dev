// cspell:ignore helpformat
package helpformat

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

func TestGeneratedExtensionFormatters(t *testing.T) {
	source, err := os.ReadFile("helpformat.go")
	require.NoError(t, err)
	for _, extension := range []string{"azure.ai.projects", "azure.ai.routines", "azure.ai.skills", "azure.ai.toolboxes"} {
		t.Run(extension, func(t *testing.T) {
			root := filepath.Join("..", "..", "..", extension)
			// #nosec G304 -- Reads only fixed, repository-owned formatter paths.
			generated, err := os.ReadFile(filepath.Join(root, "internal", "helpformat", "helpformat.go"))
			require.NoError(t, err, "run go generate ./internal/helpformat from azure.ai.connections")
			require.Equal(t,
				strings.Replace(strings.Replace(string(source), "//go:generate go run ./internal/generate\n\n", "", 1),
					"\n\n", "\n\n// Code generated by go generate ./internal/helpformat from azure.ai.connections; DO NOT EDIT.\n\n", 1),
				string(generated), "run go generate ./internal/helpformat from azure.ai.connections")
		})
	}
}
