// cspell:ignore helpformat
// Command generate keeps independently released AI extensions on the same help
// renderer without requiring an unreleased azd SDK or local module replacements.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	source, err := os.ReadFile("helpformat.go")
	if err != nil {
		return fmt.Errorf("reading canonical help formatter: %w", err)
	}
	generated := strings.Replace(strings.Replace(string(source), "//go:generate go run ./internal/generate\n\n", "", 1),
		"\n\n", "\n\n// Code generated by go generate ./internal/helpformat from azure.ai.connections; DO NOT EDIT.\n\n", 1)
	for _, extension := range []string{"azure.ai.projects", "azure.ai.routines", "azure.ai.skills", "azure.ai.toolboxes"} {
		root := filepath.Join("..", "..", "..", extension)
		dir := filepath.Join(root, "internal", "helpformat")
		if err := os.MkdirAll(dir, 0750); err != nil {
			return fmt.Errorf("creating formatter directory: %w", err)
		}
		// #nosec G703 -- Paths come from the fixed extension allowlist, not user input.
		if err := os.WriteFile(filepath.Join(dir, "helpformat.go"), []byte(generated), 0600); err != nil {
			return fmt.Errorf("writing formatter for %s: %w", root, err)
		}
	}
	return nil
}
