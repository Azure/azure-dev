func TestWindowsDirectoryAndPrivatePublication(t *testing.T) {
	directory := t.TempDir()
	parent, err := openDirectory(directory, false)
	require.NoError(t, err)
	stage, err := newStaging(parent.Root)
	require.NoError(t, err)
	require.NoError(t, stage.verify())
	require.NoError(t, stage.cleanup())
	require.NoError(t, parent.Close())
	path := filepath.Join(directory, "result")
	require.NoError(t, Write(path, []byte("private-result"), false))
	file, err := os.Open(path) //nolint:gosec // Inspect the exact file published in this test's temporary directory.
	require.NoError(t, err)
	defer file.Close()
	sd, err := windows.GetSecurityInfo(windows.Handle(file.Fd()), windows.SE_FILE_OBJECT,
		windows.OWNER_SECURITY_INFORMATION|windows.DACL_SECURITY_INFORMATION)
	require.NoError(t, err)
	trusted, err := trustedWindowsSIDs()
	require.NoError(t, err)
	require.NoError(t, verifyWindowsDescriptor(sd, trusted, false))
	acl, _, err := sd.DACL()
	require.NoError(t, err)
	assert.EqualValues(t, 3, acl.AceCount, "published files inherit only user, SYSTEM, and Administrators grants")
}

func TestWindowsDirectoryChainIsLocked(t *testing.T) {
	directory := t.TempDir()
	parent, err := openDirectory(directory, false)
	require.NoError(t, err)
	require.Error(t, os.Rename(directory, directory+"-moved"))
	require.NoError(t, parent.Close())
	require.NoError(t, os.Rename(directory, directory+"-moved"))
	require.NoError(t, os.Rename(directory+"-moved", directory))
}

func TestWindowsACLMatrix(t *testing.T) {
	trusted, err := trustedWindowsSIDs()
	require.NoError(t, err)
	owner := "O:" + trusted[0].String()
	for _, tt := range []struct {
		name, sddl string
		ancestor   bool
		allowed    bool
	}{
		{"private", owner + "D:P(A;;FA;;;" + trusted[0].String() + ")", false, true},
		{"null DACL", owner + "D:NO_ACCESS_CONTROL", false, false},
		{"untrusted owner", "O:WDD:(A;;FA;;;SY)", false, false},
		{"world read", owner + "D:(A;;FR;;;WD)", false, true},
		{"world write", owner + "D:(A;;FW;;;WD)", false, false},
		{"world delete", owner + "D:(A;;SD;;;WD)", false, false},
		{"world delete children", owner + "D:(A;;0x40;;;WD)", false, false},
		{"world change permissions", owner + "D:(A;;WD;;;WD)", false, false},
		{"ancestor create only", owner + "D:(A;;0x4;;;WD)", true, true},
		{"leaf create", owner + "D:(A;;0x4;;;WD)", false, false},
		{"ancestor delete children", owner + "D:(A;;0x40;;;WD)", true, false},
		{"deny", owner + "D:(D;;FA;;;WD)", false, true},
	} {
		t.Run(tt.name, func(t *testing.T) {
			sd, err := windows.SecurityDescriptorFromString(tt.sddl)
			require.NoError(t, err)
			err = verifyWindowsDescriptor(sd, trusted, tt.ancestor)
			if tt.allowed {
				require.NoError(t, err)
			} else {
				require.Error(t, err)
			}
		})
	}
}

func TestWindowsRejectsSharedOutput(t *testing.T) {
	directory := t.TempDir()
	sd, err := windows.SecurityDescriptorFromString("D:P(A;OICI;FA;;;WD)")
	require.NoError(t, err)
	acl, _, err := sd.DACL()
	require.NoError(t, err)
	require.NoError(t, windows.SetNamedSecurityInfo(directory, windows.SE_FILE_OBJECT,
		windows.DACL_SECURITY_INFORMATION|windows.PROTECTED_DACL_SECURITY_INFORMATION, nil, nil, acl, nil))
	require.Error(t, Write(filepath.Join(directory, "result"), []byte("private"), false))
	entries, err := os.ReadDir(directory)
	require.NoError(t, err)
	assert.Empty(t, entries)
}

func TestWindowsRejectsJunctionRedirection(t *testing.T) {
	directory := t.TempDir()
	target, link := filepath.Join(directory, "target"), filepath.Join(directory, "junction")
	require.NoError(t, os.Mkdir(target, 0o700))
	// #nosec G204 -- All arguments are fixed or generated by this test.
	output, err := exec.Command("cmd.exe", "/c", "mklink", "/J", link, target).CombinedOutput()
	require.NoError(t, err, string(output))
	_, err = Check(filepath.Join(link, "result"))
	require.Error(t, err)
	require.Error(t, Write(filepath.Join(link, "result"), []byte("private"), false))
	entries, err := os.ReadDir(target)
	require.NoError(t, err)
	assert.Empty(t, entries)
}
