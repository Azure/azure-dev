package cmd

import (
	"context"
	"errors"
	"fmt"
	"os"
	"strings"

	"azureaidataset/internal/pkg/dataset_api"
	"azureaidataset/internal/pkg/gen_api"

	"github.com/Azure/azure-sdk-for-go/sdk/azcore"
	"github.com/Azure/azure-sdk-for-go/sdk/azidentity"
	"github.com/azure/azure-dev/cli/azd/pkg/azdext"
)

// projectEndpointEnvKey is the azd environment key holding the Foundry project
// endpoint the data-plane clients target.
const projectEndpointEnvKey = "FOUNDRY_PROJECT_ENDPOINT"

// appInsightsEnvKey is where a connected Application Insights resource lands in
// the azd environment, and so how a project says it collects traces at all.
const appInsightsEnvKey = "APPLICATIONINSIGHTS_CONNECTION_STRING"

// datasetContext carries everything the commands need to reach the data plane.
//
// Two clients, because a dataset is registered through the dataset API but
// generated by the evaluation service.
type datasetContext struct {
	azdClient *azdext.AzdClient
	endpoint  string
	envName   string
	cred      azcore.TokenCredential

	datasetClient *dataset_api.DatasetClient
	genClient     *gen_api.Client
}

// newDatasetContext resolves the project endpoint and builds the data-plane
// clients. Endpoint resolution order:
//
//  1. --project-endpoint
//  2. the active azd environment's FOUNDRY_PROJECT_ENDPOINT
//  3. the host environment variable of the same name
func newDatasetContext(ctx context.Context, endpointFlag string) (*datasetContext, error) {
	azdClient, err := azdext.NewAzdClient()
	if err != nil {
		return nil, fmt.Errorf("connecting to azd: %w", err)
	}

	dc := &datasetContext{azdClient: azdClient}

	// The environment name is resolved regardless of where the endpoint came
	// from: it is what cached version numbers are read from and written to.
	azdEndpoint, envName := lookupEndpointFromAzd(ctx, azdClient)
	dc.envName = envName

	if endpointFlag != "" {
		dc.endpoint = endpointFlag
	} else {
		dc.endpoint = azdEndpoint
	}
	if dc.endpoint == "" {
		dc.endpoint = os.Getenv(projectEndpointEnvKey)
	}
	if dc.endpoint == "" {
		return nil, fmt.Errorf(
			"no Foundry project endpoint found; pass --project-endpoint or set %s "+
				"in the azd environment (azd env set %s <url>)",
			projectEndpointEnvKey, projectEndpointEnvKey)
	}
	dc.endpoint = strings.TrimSuffix(dc.endpoint, "/")

	cred, err := azidentity.NewAzureDeveloperCLICredential(
		&azidentity.AzureDeveloperCLICredentialOptions{},
	)
	if err != nil {
		return nil, fmt.Errorf("creating Azure credential: %w", err)
	}
	dc.cred = cred

	dc.datasetClient = dataset_api.NewDatasetClient(dc.endpoint, cred)
	dc.genClient = gen_api.NewClient(dc.endpoint, cred)

	return dc, nil
}

// lookupEndpointFromAzd reads the endpoint from the active azd environment,
// returning empty strings when azd has no current environment.
func lookupEndpointFromAzd(ctx context.Context, azdClient *azdext.AzdClient) (endpoint, envName string) {
	envResp, err := azdClient.Environment().GetCurrent(ctx, &azdext.EmptyRequest{})
	if err != nil || envResp == nil || envResp.Environment == nil {
		return "", ""
	}
	val, err := azdClient.Environment().GetValue(ctx, &azdext.GetEnvRequest{
		EnvName: envResp.Environment.Name,
		Key:     projectEndpointEnvKey,
	})
	if err != nil || val == nil || val.Value == "" {
		return "", envResp.Environment.Name
	}
	return val.Value, envResp.Environment.Name
}

// errNoAzdEnvironment reports that there is no azd environment to persist into.
//
// These commands work standalone against the data plane, so running outside a
// project is ordinary rather than a problem worth reporting.
var errNoAzdEnvironment = errors.New("no active azd environment")

// setEnvValue persists a value into the active azd environment.
func (dc *datasetContext) setEnvValue(ctx context.Context, key, value string) error {
	if dc.envName == "" {
		envResp, err := dc.azdClient.Environment().GetCurrent(ctx, &azdext.EmptyRequest{})
		if err != nil || envResp == nil || envResp.Environment == nil {
			return fmt.Errorf("%w to write %s into", errNoAzdEnvironment, key)
		}
		dc.envName = envResp.Environment.Name
	}
	_, err := dc.azdClient.Environment().SetValue(ctx, &azdext.SetEnvRequest{
		EnvName: dc.envName,
		Key:     key,
		Value:   value,
	})
	if err != nil {
		return fmt.Errorf("writing %s to the azd environment: %w", key, err)
	}
	return nil
}

// getEnvValue reads a value from the active azd environment, returning empty
// when it is unset.
func (dc *datasetContext) getEnvValue(ctx context.Context, key string) string {
	if dc.envName == "" {
		return ""
	}
	val, err := dc.azdClient.Environment().GetValue(ctx, &azdext.GetEnvRequest{
		EnvName: dc.envName,
		Key:     key,
	})
	if err != nil || val == nil {
		return ""
	}
	return val.Value
}

func (dc *datasetContext) Close() {
	if dc.azdClient != nil {
		dc.azdClient.Close()
	}
}
