package eval_api

// EvalRunDataSourceTypeUserConversationSimulation runs a simulated user against
// the target agent, one conversation per scenario seed.
//
// This value is provisional. The portal uses it today and the GA TypeSpec has
// not landed, so it is declared alone here: confirming the discriminator is a
// one-line change rather than a search. Nothing may fall back to
// azure_ai_target_completions when this is the intended shape -- that is the
// turn-level data source, and it would invoke the agent once with an empty
// question instead of holding a conversation.
const EvalRunDataSourceTypeUserConversationSimulation EvalRunDataSourceType = //
"azure_ai_user_conversation_simulation_preview"

// ModelConfiguration names the deployment the simulated user speaks with. It is
// not the judge model an evaluator initializes.
type ModelConfiguration struct {
	Model string `json:"model,omitempty"`
}

// SimulationConfiguration bounds the conversations a run creates.
type SimulationConfiguration struct {
	// ConversationRepetitions is how many conversations to create per seed.
	ConversationRepetitions int `json:"conversation_repetitions,omitempty"`

	// MaxNumTurns bounds each conversation. Omitted leaves the service's
	// default rather than truncating at a number the caller never chose.
	MaxNumTurns int `json:"max_num_turns,omitempty"`

	// EnableConversationDatasetGeneration is false: the azd workflow is staged,
	// so seeds are generated by `eval generate` and a run only consumes them.
	// Sent explicitly rather than omitted, because this is a decision and not
	// an oversight.
	EnableConversationDatasetGeneration bool `json:"enable_conversation_dataset_generation"`
}

// NewSimulationDataSource builds the data source for a run that creates its
// conversations from a registered seed dataset.
//
// It carries no input-message template on purpose. A seed row describes a
// conversation to have; there is no question on it to bind, and binding one
// would invoke the agent with an empty string.
//
// The rows are not supplied here: a registered dataset is bound by id through
// SetFileID, because copying its rows into the request loses the version
// binding the run is supposed to record.
func NewSimulationDataSource(
	agentName string,
	model string,
	conversationRepetitions int,
	maxTurns int,
) *EvalRunDataSource {
	return &EvalRunDataSource{
		Type: EvalRunDataSourceTypeUserConversationSimulation,
		Target: &EvalRunTarget{
			Type: "azure_ai_agent",
			Name: agentName,
		},
		ModelConfiguration: &ModelConfiguration{Model: model},
		DefaultSimulationConfiguration: &SimulationConfiguration{
			ConversationRepetitions:             conversationRepetitions,
			MaxNumTurns:                         maxTurns,
			EnableConversationDatasetGeneration: false,
		},
	}
}
