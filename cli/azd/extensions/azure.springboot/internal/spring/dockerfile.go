const springDockerfile = `# Generated by azure.springboot. Do not edit; configure the service in azure.yaml.
FROM eclipse-temurin:17.0.17_10-jre-jammy
RUN groupadd --system spring && useradd --system --gid spring --home-dir /app spring
WORKDIR /app
COPY --chown=spring:spring .azd-springboot/app.jar /app/application.jar
USER spring:spring
EXPOSE 8080
ENTRYPOINT ["java", "-jar", "/app/application.jar"]
`

const legacySpringDockerfile = `# Generated by azure.springboot. Do not edit; configure the service in azure.yaml.
FROM eclipse-temurin:17.0.17_10-jdk-jammy AS build
WORKDIR /workspace
COPY .mvn/ .mvn/
COPY mvnw pom.xml ./
RUN chmod +x mvnw && ./mvnw -B -ntp dependency:go-offline
COPY src/ src/
RUN ./mvnw -B -ntp -DskipTests package \
    && JAR="$(find target -maxdepth 1 -type f -name '*.jar' ! -name '*.original' -print -quit)" \
    && test -n "$JAR" \
    && cp "$JAR" /workspace/application.jar

FROM eclipse-temurin:17.0.17_10-jre-jammy
RUN groupadd --system spring && useradd --system --gid spring --home-dir /app spring
WORKDIR /app
COPY --from=build --chown=spring:spring /workspace/application.jar /app/application.jar
USER spring:spring
EXPOSE 8080
ENTRYPOINT ["java", "-jar", "/app/application.jar"]
`

const (
	stagingDirectoryName = ".azd-springboot"
	stagedJarName        = "app.jar"
)

type dockerfileOwnership int

const (
	dockerfileMissing dockerfileOwnership = iota
	dockerfileCurrent
	dockerfileLegacy
)

type stagedContainerContext struct {
	directory string
	jarPath   string
	jarHash   [sha256.Size]byte
}

func servicePath(project *azdext.ProjectConfig, service *azdext.ServiceConfig) (string, error) {
	if project == nil || project.Path == "" {
		return "", validationError("missing_project_path", "project path is missing", "run the command from an azd project")
	}
	if service == nil {
		return "", validationError("missing_service_config", "service configuration is missing", "check azure.yaml")
	}

	projectPath, err := filepath.Abs(project.Path)
	if err != nil {
		return "", fmt.Errorf("resolving project path: %w", err)
	}
	projectPath, err = filepath.EvalSymlinks(projectPath)
	if err != nil {
		return "", fmt.Errorf("resolving project path links: %w", err)
	}
	relativePath := service.RelativePath
	if relativePath == "" {
		relativePath = "."
	}
	if filepath.IsAbs(relativePath) {
		return "", validationError(
			"invalid_service_path",
			fmt.Sprintf("service %q project path must be relative", service.Name),
			"use a project path contained within the azd project",
		)
	}
	servicePath := filepath.Join(projectPath, filepath.Clean(relativePath))
	servicePath, err = filepath.EvalSymlinks(servicePath)
	if err != nil {
		return "", validationError(
			"invalid_service_path",
			fmt.Sprintf("service %q project path cannot be resolved", service.Name),
			"use an existing project path contained within the azd project",
		)
	}
	if !osutil.IsPathContained(projectPath, servicePath) {
		return "", validationError(
			"invalid_service_path",
			fmt.Sprintf("service %q project path resolves outside the azd project", service.Name),
			"use a project path contained within the azd project",
		)
	}

	required := []string{
		"pom.xml",
		"mvnw",
		filepath.Join(".mvn", "wrapper", "maven-wrapper.properties"),
		"src",
	}
	for _, path := range required {
		if _, err := os.Stat(filepath.Join(servicePath, path)); err != nil {
			return "", validationError(
				"unsupported_spring_project",
				fmt.Sprintf("service %q is missing required Maven project path %q", service.Name, path),
				"azure.springboot currently requires a Maven Wrapper, pom.xml, and src directory",
			)
		}
	}
	return servicePath, nil
}

func dockerfilePath(project *azdext.ProjectConfig, service *azdext.ServiceConfig) (string, error) {
	path, err := servicePath(project, service)
	if err != nil {
		return "", err
	}
	return filepath.Join(path, "Dockerfile"), nil
}

func inspectDockerfile(
	project *azdext.ProjectConfig,
	service *azdext.ServiceConfig,
) (string, dockerfileOwnership, error) {
	path, err := dockerfilePath(project, service)
	if err != nil {
		return "", dockerfileMissing, err
	}
	info, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return path, dockerfileMissing, nil
	}
	if err != nil {
		return "", dockerfileMissing, fmt.Errorf("inspecting Dockerfile for service %q: %w", service.Name, err)
	}
	if !info.Mode().IsRegular() {
		return "", dockerfileMissing, validationError(
			"unsafe_dockerfile",
			fmt.Sprintf("service %q Dockerfile must be a regular file", service.Name),
			"replace the Dockerfile link or special file with a regular file, or remove it",
		)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return "", dockerfileMissing, fmt.Errorf("reading Dockerfile for service %q: %w", service.Name, err)
	}
	switch {
	case bytes.Equal(data, []byte(springDockerfile)):
		return path, dockerfileCurrent, nil
	case bytes.Equal(data, []byte(legacySpringDockerfile)):
		return path, dockerfileLegacy, nil
	default:
		return "", dockerfileMissing, validationError(
			"conflicting_dockerfile",
			fmt.Sprintf("service %q already has a Dockerfile not owned by azure.springboot", service.Name),
			"remove or rename the Dockerfile, or use host: containerapp with explicit Docker settings",
		)
	}
}

func validateDockerfile(project *azdext.ProjectConfig, service *azdext.ServiceConfig) (string, bool, error) {
	path, ownership, err := inspectDockerfile(project, service)
	return path, ownership != dockerfileMissing, err
}

func ensureDockerfile(project *azdext.ProjectConfig, service *azdext.ServiceConfig) error {
	path, ownership, err := inspectDockerfile(project, service)
	if err != nil || ownership == dockerfileCurrent {
		return err
	}

	dir := filepath.Dir(path)
	temp, err := os.CreateTemp(dir, ".azd-springboot-Dockerfile-*")
	if err != nil {
		return fmt.Errorf("creating temporary Dockerfile: %w", err)
	}
	tempPath := temp.Name()
	defer os.Remove(tempPath)

	if _, err := temp.WriteString(springDockerfile); err != nil {
		_ = temp.Close()
		return fmt.Errorf("writing temporary Dockerfile: %w", err)
	}
	if err := temp.Sync(); err != nil {
		_ = temp.Close()
		return fmt.Errorf("syncing temporary Dockerfile: %w", err)
	}
	if err := temp.Close(); err != nil {
		return fmt.Errorf("closing temporary Dockerfile: %w", err)
	}
	if err := os.Chmod(tempPath, osutil.PermissionFile); err != nil {
		return fmt.Errorf("setting temporary Dockerfile permissions: %w", err)
	}

	if ownership == dockerfileLegacy {
		legacyPath := tempPath + ".legacy"
		if err := os.Link(path, legacyPath); err != nil {
			return fmt.Errorf("preserving the legacy generated Dockerfile: %w", err)
		}
		defer os.Remove(legacyPath)

		_, currentOwnership, err := inspectDockerfile(project, service)
		if err != nil {
			return err
		}
		if currentOwnership != dockerfileLegacy {
			return validationError(
				"dockerfile_changed_during_migration",
				fmt.Sprintf("service %q Dockerfile changed while azure.springboot was preparing it", service.Name),
				"retry after confirming the Dockerfile is not being modified",
			)
		}
		if err := os.Remove(path); err != nil {
			return fmt.Errorf("removing the legacy generated Dockerfile: %w", err)
		}
		if err := os.Link(tempPath, path); err != nil {
			if restoreErr := os.Link(legacyPath, path); restoreErr != nil && !errors.Is(restoreErr, os.ErrExist) {
				return errors.Join(
					fmt.Errorf("publishing the runtime Dockerfile: %w", err),
					fmt.Errorf("restoring the legacy generated Dockerfile: %w", restoreErr),
				)
			}
			return fmt.Errorf("publishing the runtime Dockerfile: %w", err)
		}
		return nil
	}

	// A hard link publishes the complete file without replacing a user-created file that won the race.
	if err := os.Link(tempPath, path); err != nil {
		_, currentOwnership, validationErr := inspectDockerfile(project, service)
		if validationErr != nil {
			return validationErr
		}
		if currentOwnership == dockerfileCurrent {
			return nil
		}
		return fmt.Errorf("publishing generated Dockerfile: %w", err)
	}
	return nil
}

func validateContainerSettings(service *azdext.ServiceConfig) error {
	if service == nil {
		return validationError("missing_service_config", "service configuration is missing", "check azure.yaml")
	}
	docker := service.GetDocker()
	if docker == nil {
		return nil
	}
	if docker.GetRemoteBuild() {
		return validationError(
			"remote_container_build_unsupported",
			fmt.Sprintf("service %q enables docker.remoteBuild, which azure.springboot does not support", service.Name),
			"remove docker.remoteBuild or set it to false",
		)
	}
	if docker.GetPath() != "" || docker.GetContext() != "" || docker.GetTarget() != "" ||
		docker.GetImage() != "" || docker.GetImagePassthrough() || len(docker.GetBuildArgs()) > 0 {
		return validationError(
			"custom_docker_settings_unsupported",
			fmt.Sprintf("service %q defines Docker settings that azure.springboot cannot apply", service.Name),
			"remove the service docker block or use host: containerapp",
		)
	}
	return nil
}

func validateDockerContext(serviceDir string) error {
	ignorePath := filepath.Join(serviceDir, ".dockerignore")
	file, err := os.Open(ignorePath)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("opening .dockerignore: %w", err)
	}
	defer file.Close()

	patterns, err := ignorefile.ReadAll(file)
	if err != nil {
		return fmt.Errorf("reading .dockerignore: %w", err)
	}
	matcher, err := patternmatcher.New(patterns)
	if err != nil {
		return validationError(
			"invalid_dockerignore",
			fmt.Sprintf("the service .dockerignore is invalid: %v", err),
			"fix .dockerignore so Dockerfile and .azd-springboot/app.jar are included",
		)
	}
	for _, path := range []string{"Dockerfile", filepath.ToSlash(filepath.Join(stagingDirectoryName, stagedJarName))} {
		ignored, err := matcher.MatchesOrParentMatches(path)
		if err != nil {
			return fmt.Errorf("matching %q against .dockerignore: %w", path, err)
		}
		if ignored {
			return validationError(
				"spring_build_context_ignored",
				fmt.Sprintf("the service .dockerignore excludes required build path %q", path),
				"update .dockerignore so Dockerfile and .azd-springboot/app.jar are included",
			)
		}
	}
	return nil
}

func findMavenJar(serviceContext *azdext.ServiceContext) (string, error) {
	if serviceContext == nil {
		return "", validationError(
			"missing_service_context",
			"the service package context is missing",
			"rerun azd package so the Maven package is produced before container packaging",
		)
	}
	var packageDirectory string
	for _, artifact := range serviceContext.GetPackage() {
		if artifact == nil ||
			artifact.GetKind() != azdext.ArtifactKind_ARTIFACT_KIND_DIRECTORY ||
			artifact.GetLocationKind() != azdext.LocationKind_LOCATION_KIND_LOCAL ||
			artifact.GetMetadata()["framework"] != "maven" {
			continue
		}
		if packageDirectory != "" {
			return "", validationError(
				"ambiguous_maven_package",
				"more than one Maven package artifact was supplied for the Spring service",
				"remove duplicate package artifacts and retry",
			)
		}
		packageDirectory = artifact.GetLocation()
	}
	if packageDirectory == "" {
		return "", validationError(
			"missing_maven_package",
			"the Spring service did not produce a local Maven package directory",
			"verify language: java and rerun azd package",
		)
	}

	resolvedDirectory, err := filepath.EvalSymlinks(packageDirectory)
	if err != nil {
		return "", fmt.Errorf("resolving Maven package directory: %w", err)
	}
	info, err := os.Stat(resolvedDirectory)
	if err != nil {
		return "", fmt.Errorf("reading Maven package directory: %w", err)
	}
	if !info.IsDir() {
		return "", validationError(
			"invalid_maven_package",
			"the Maven package artifact is not a directory",
			"rerun azd package and verify the Java package output",
		)
	}

	jarPath := filepath.Join(resolvedDirectory, stagedJarName)
	linkInfo, err := os.Lstat(jarPath)
	if err != nil {
		return "", validationError(
			"missing_maven_jar",
			"the Maven package directory does not contain app.jar",
			"configure Maven to produce a Spring Boot JAR and rerun azd package",
		)
	}
	if linkInfo.Mode()&os.ModeSymlink != 0 || !linkInfo.Mode().IsRegular() {
		return "", validationError(
			"invalid_maven_jar",
			"the packaged app.jar must be a regular file, not a link or special file",
			"rerun azd package with a regular Spring Boot JAR",
		)
	}
	resolvedJar, err := filepath.EvalSymlinks(jarPath)
	if err != nil {
		return "", fmt.Errorf("resolving packaged app.jar: %w", err)
	}
	if !osutil.IsPathContained(resolvedDirectory, resolvedJar) {
		return "", validationError(
			"invalid_maven_jar",
			"the packaged app.jar resolves outside its package directory",
			"rerun azd package with a self-contained Spring Boot JAR",
		)
	}
	return resolvedJar, nil
}

func prepareContainerContext(
	ctx context.Context,
	project *azdext.ProjectConfig,
	service *azdext.ServiceConfig,
	serviceContext *azdext.ServiceContext,
) (*stagedContainerContext, error) {
	if err := validateContainerSettings(service); err != nil {
		return nil, err
	}
	serviceDir, err := servicePath(project, service)
	if err != nil {
		return nil, err
	}
	if err := validateDockerContext(serviceDir); err != nil {
		return nil, err
	}
	if _, _, err := inspectDockerfile(project, service); err != nil {
		return nil, err
	}
	jarPath, err := findMavenJar(serviceContext)
	if err != nil {
		return nil, err
	}

	stagingDir := filepath.Join(serviceDir, stagingDirectoryName)
	if err := os.Mkdir(stagingDir, osutil.PermissionDirectoryOwnerOnly); err != nil {
		if errors.Is(err, os.ErrExist) {
			return nil, validationError(
				"spring_build_context_collision",
				fmt.Sprintf("service %q already contains %s", service.Name, stagingDirectoryName),
				"remove the directory if it is stale and retry; azure.springboot never overwrites it",
			)
		}
		return nil, fmt.Errorf("creating Spring container build context: %w", err)
	}

	staged := &stagedContainerContext{
		directory: stagingDir,
		jarPath:   filepath.Join(stagingDir, stagedJarName),
	}
	cleanupOnError := func() {
		_ = staged.cleanup()
	}

	staged.jarHash, err = copyFileWithContext(ctx, jarPath, staged.jarPath)
	if err != nil {
		_ = os.Remove(staged.jarPath)
		_ = os.Remove(staged.directory)
		return nil, err
	}
	if err := ensureDockerfile(project, service); err != nil {
		cleanupOnError()
		return nil, err
	}
	return staged, nil
}

func copyFileWithContext(ctx context.Context, source, destination string) ([sha256.Size]byte, error) {
	var sum [sha256.Size]byte
	sourceFile, err := os.Open(source)
	if err != nil {
		return sum, fmt.Errorf("opening packaged app.jar: %w", err)
	}
	defer sourceFile.Close()

	destinationFile, err := os.OpenFile(destination, os.O_CREATE|os.O_EXCL|os.O_WRONLY, osutil.PermissionFileOwnerOnly)
	if err != nil {
		return sum, fmt.Errorf("creating staged app.jar: %w", err)
	}

	hash := sha256.New()
	writer := io.MultiWriter(destinationFile, hash)
	buffer := make([]byte, 128*1024)
	for {
		if err := ctx.Err(); err != nil {
			_ = destinationFile.Close()
			return sum, err
		}
		count, readErr := sourceFile.Read(buffer)
		if count > 0 {
			if _, err := writer.Write(buffer[:count]); err != nil {
				_ = destinationFile.Close()
				return sum, fmt.Errorf("staging packaged app.jar: %w", err)
			}
		}
		if errors.Is(readErr, io.EOF) {
			break
		}
		if readErr != nil {
			_ = destinationFile.Close()
			return sum, fmt.Errorf("reading packaged app.jar: %w", readErr)
		}
	}
	if err := destinationFile.Sync(); err != nil {
		_ = destinationFile.Close()
		return sum, fmt.Errorf("syncing staged app.jar: %w", err)
	}
	if err := destinationFile.Close(); err != nil {
		return sum, fmt.Errorf("closing staged app.jar: %w", err)
	}
	copy(sum[:], hash.Sum(nil))
	return sum, nil
}

func (s *stagedContainerContext) cleanup() error {
	if s == nil {
		return nil
	}
	file, err := os.Open(s.jarPath)
	if err == nil {
		hash := sha256.New()
		if _, copyErr := io.Copy(hash, file); copyErr != nil {
			_ = file.Close()
			return fmt.Errorf("verifying staged app.jar before cleanup: %w", copyErr)
		}
		if closeErr := file.Close(); closeErr != nil {
			return fmt.Errorf("closing staged app.jar before cleanup: %w", closeErr)
		}
		if !bytes.Equal(hash.Sum(nil), s.jarHash[:]) {
			return validationError(
				"spring_build_context_changed",
				fmt.Sprintf("%s changed during the container build", s.jarPath),
				"remove the staging directory after preserving any unexpected changes, then retry",
			)
		}
		if err := os.Remove(s.jarPath); err != nil {
			return fmt.Errorf("removing staged app.jar: %w", err)
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("opening staged app.jar for cleanup: %w", err)
	}
	if err := os.Remove(s.directory); err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("removing Spring container build context: %w", err)
	}
	return nil
}
