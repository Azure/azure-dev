const springDockerfile = `# Generated by azure.springboot. Do not edit; configure the service in azure.yaml.
FROM eclipse-temurin:17.0.17_10-jre-jammy
RUN groupadd --system spring && useradd --system --gid spring --home-dir /app spring
WORKDIR /app
COPY --chown=spring:spring app.jar /app/application.jar
USER spring:spring
EXPOSE 8080
ENTRYPOINT ["java", "-jar", "/app/application.jar"]
`

const (
	stagingDirectoryName         = ".azd-springboot"
	stagedJarName                = "app.jar"
	springApplicationClassesPath = "BOOT-INF/classes/"
	java17ClassMajorVersion      = 61
)

type stagedContainerContext struct {
	directory  string
	info       os.FileInfo
	jarPath    string
	recipePath string
	jarHash    [sha256.Size]byte
}

func servicePath(project *azdext.ProjectConfig, service *azdext.ServiceConfig) (string, error) {
	if project == nil || project.Path == "" {
		return "", validationError("missing_project_path", "project path is missing", "run the command from an azd project")
	}
	if service == nil {
		return "", validationError("missing_service_config", "service configuration is missing", "check azure.yaml")
	}

	projectPath, err := filepath.Abs(project.Path)
	if err != nil {
		return "", fmt.Errorf("resolving project path: %w", err)
	}
	projectPath, err = filepath.EvalSymlinks(projectPath)
	if err != nil {
		return "", fmt.Errorf("resolving project path links: %w", err)
	}
	relativePath := service.RelativePath
	if relativePath == "" {
		relativePath = "."
	}
	if filepath.IsAbs(relativePath) {
		return "", validationError(
			"invalid_service_path",
			fmt.Sprintf("service %q project path must be relative", service.Name),
			"use a project path contained within the azd project",
		)
	}
	servicePath := filepath.Join(projectPath, filepath.Clean(relativePath))
	servicePath, err = filepath.EvalSymlinks(servicePath)
	if err != nil {
		return "", validationError(
			"invalid_service_path",
			fmt.Sprintf("service %q project path cannot be resolved", service.Name),
			"use an existing project path contained within the azd project",
		)
	}
	if !osutil.IsPathContained(projectPath, servicePath) {
		return "", validationError(
			"invalid_service_path",
			fmt.Sprintf("service %q project path resolves outside the azd project", service.Name),
			"use a project path contained within the azd project",
		)
	}

	if err := validateJavaBuild(servicePath, service.Name); err != nil {
		return "", err
	}
	return servicePath, nil
}

func findSpringJar(serviceContext *azdext.ServiceContext, root string) (string, error) {
	system, err := detectJavaBuild(root)
	if err != nil {
		return "", err
	}
	return findJavaJar(serviceContext, system)
}

func findJavaJar(serviceContext *azdext.ServiceContext, system javaBuildSystem) (string, error) {
	label := "Maven"
	if system == gradleBuild {
		label = "Gradle"
	}
	if serviceContext == nil {
		return "", validationError(
			"missing_service_context",
			"the service package context is missing",
			"rerun azd package so the Java package is produced before container packaging",
		)
	}
	var packageDirectory string
	for _, artifact := range serviceContext.GetPackage() {
		if artifact == nil ||
			artifact.GetKind() != azdext.ArtifactKind_ARTIFACT_KIND_DIRECTORY ||
			artifact.GetLocationKind() != azdext.LocationKind_LOCATION_KIND_LOCAL {
			continue
		}
		framework := artifact.GetMetadata()["framework"]
		if framework != string(system) {
			if framework == string(mavenBuild) || framework == string(gradleBuild) {
				return "", validationError("mismatched_java_package", "the Java package uses a different build system",
					"rerun azd package with only the current service's package artifacts")
			}
			continue
		}
		if strings.TrimSpace(artifact.GetLocation()) == "" {
			return "", validationError("invalid_"+string(system)+"_package", "the Java package artifact has no location",
				"rerun azd package to produce one local Java package directory")
		}
		if packageDirectory != "" {
			return "", validationError(
				"ambiguous_"+string(system)+"_package",
				"more than one "+label+" package artifact was supplied for the Spring service",
				"remove duplicate package artifacts and retry",
			)
		}
		packageDirectory = artifact.GetLocation()
	}
	if packageDirectory == "" {
		return "", validationError(
			"missing_"+string(system)+"_package",
			"the Spring service did not produce a local "+label+" package directory",
			"verify language: java and rerun azd package",
		)
	}

	resolvedDirectory, err := filepath.EvalSymlinks(packageDirectory)
	if err != nil {
		return "", fmt.Errorf("resolving Java package directory: %w", err)
	}
	info, err := os.Stat(resolvedDirectory)
	if err != nil {
		return "", fmt.Errorf("reading Java package directory: %w", err)
	}
	if !info.IsDir() {
		return "", validationError(
			"invalid_"+string(system)+"_package",
			"the "+label+" package artifact is not a directory",
			"rerun azd package and verify the Java package output",
		)
	}

	jarPath := filepath.Join(resolvedDirectory, stagedJarName)
	linkInfo, err := os.Lstat(jarPath)
	if err != nil {
		return "", validationError(
			"missing_"+string(system)+"_jar",
			"the "+label+" package directory does not contain app.jar",
			"configure the build to produce a Spring Boot JAR and rerun azd package",
		)
	}
	if linkInfo.Mode()&os.ModeSymlink != 0 || !linkInfo.Mode().IsRegular() {
		return "", validationError(
			"invalid_"+string(system)+"_jar",
			"the packaged app.jar must be a regular file, not a link or special file",
			"rerun azd package with a regular Spring Boot JAR",
		)
	}
	resolvedJar, err := filepath.EvalSymlinks(jarPath)
	if err != nil {
		return "", fmt.Errorf("resolving packaged app.jar: %w", err)
	}
	if !osutil.IsPathContained(resolvedDirectory, resolvedJar) {
		return "", validationError(
			"invalid_"+string(system)+"_jar",
			"the packaged app.jar resolves outside its package directory",
			"rerun azd package with a self-contained Spring Boot JAR",
		)
	}
	return resolvedJar, nil
}

func validateSpringJarRuntime(ctx context.Context, jarPath string) (err error) {
	if err := ctx.Err(); err != nil {
		return err
	}
	archive, err := zip.OpenReader(jarPath)
	if err != nil {
		return validationError(
			"invalid_maven_jar",
			"the packaged app.jar is not a valid JAR archive",
			"configure the build to produce an executable Spring Boot JAR and rerun azd package",
		)
	}
	defer func() {
		err = errors.Join(err, archive.Close())
	}()

	for _, entry := range archive.File {
		if err := ctx.Err(); err != nil {
			return err
		}
		if !strings.HasPrefix(entry.Name, springApplicationClassesPath) ||
			!strings.HasSuffix(entry.Name, ".class") {
			continue
		}

		classFile, err := entry.Open()
		if err != nil {
			return fmt.Errorf("opening packaged application class: %w", err)
		}
		var header [8]byte
		_, readErr := io.ReadFull(classFile, header[:])
		if err := errors.Join(readErr, classFile.Close()); err != nil {
			return validationError(
				"invalid_maven_jar",
				"a packaged application class is invalid",
				"configure the build to produce a valid executable Spring Boot JAR and rerun azd package",
			)
		}
		if binary.BigEndian.Uint32(header[:4]) != 0xcafebabe {
			return validationError(
				"invalid_maven_jar",
				"a packaged application class has an invalid class header",
				"configure the build to produce a valid executable Spring Boot JAR and rerun azd package",
			)
		}

		majorVersion := binary.BigEndian.Uint16(header[6:8])
		if majorVersion > java17ClassMajorVersion {
			javaVersion := int(majorVersion) - 44
			return validationError(
				"unsupported_java_runtime",
				fmt.Sprintf(
					"packaged application bytecode requires Java %d, but the generated runtime uses Java 17",
					javaVersion,
				),
				"set the Java compiler release to Java 17 and rerun azd package",
			)
		}
	}
	return nil
}

func prepareContainerContext(
	ctx context.Context,
	project *azdext.ProjectConfig,
	service *azdext.ServiceConfig,
	serviceContext *azdext.ServiceContext,
) (*stagedContainerContext, error) {
	if err := validateServiceConfiguration(service); err != nil {
		return nil, err
	}
	root, err := servicePath(project, service)
	if err != nil {
		return nil, err
	}
	jarPath, err := findSpringJar(serviceContext, root)
	if err != nil {
		return nil, err
	}
	if err := validateSpringJarRuntime(ctx, jarPath); err != nil {
		return nil, err
	}
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	stagingDir, err := os.MkdirTemp("", stagingDirectoryName+"-")
	if err != nil {
		return nil, fmt.Errorf("creating Spring container build context: %w", err)
	}

	staged := &stagedContainerContext{
		directory:  stagingDir,
		jarPath:    filepath.Join(stagingDir, stagedJarName),
		recipePath: filepath.Join(stagingDir, "Dockerfile"),
	}
	directory, err := os.Open(stagingDir)
	if err != nil {
		return nil, errors.Join(fmt.Errorf("opening Spring container build context: %w", err), os.Remove(stagingDir))
	}
	staged.info, err = directory.Stat()
	err = errors.Join(err, directory.Close())
	if err != nil {
		return nil, errors.Join(fmt.Errorf("inspecting Spring container build context: %w", err), os.Remove(stagingDir))
	}

	var copied bool
	staged.jarHash, copied, err = copyFileWithContext(ctx, jarPath, staged.jarPath)
	if err != nil {
		if copied {
			err = errors.Join(err, removeContextFile(staged.jarPath))
		}
		return nil, errors.Join(err, os.Remove(staged.directory))
	}
	recipe, err := os.OpenFile(staged.recipePath, os.O_CREATE|os.O_EXCL|os.O_WRONLY, osutil.PermissionFileOwnerOnly)
	if err != nil {
		return nil, errors.Join(
			fmt.Errorf("creating generated runtime recipe: %w", err),
			removeContextFile(staged.jarPath), os.Remove(staged.directory),
		)
	}
	_, writeErr := recipe.WriteString(springDockerfile)
	if err := errors.Join(writeErr, recipe.Close()); err != nil {
		return nil, errors.Join(fmt.Errorf("writing generated runtime recipe: %w", err),
			removeContextFile(staged.recipePath), removeContextFile(staged.jarPath), os.Remove(staged.directory))
	}
	return staged, nil
}

func copyFileWithContext(ctx context.Context, source, destination string) ([sha256.Size]byte, bool, error) {
	var sum [sha256.Size]byte
	sourceFile, err := os.Open(source)
	if err != nil {
		return sum, false, fmt.Errorf("opening packaged app.jar: %w", err)
	}
	defer sourceFile.Close()

	destinationFile, err := os.OpenFile(destination, os.O_CREATE|os.O_EXCL|os.O_WRONLY, osutil.PermissionFileOwnerOnly)
	if err != nil {
		return sum, false, fmt.Errorf("creating staged app.jar: %w", err)
	}

	hash := sha256.New()
	writer := io.MultiWriter(destinationFile, hash)
	buffer := make([]byte, 128*1024)
	for {
		if err := ctx.Err(); err != nil {
			_ = destinationFile.Close()
			return sum, true, err
		}
		count, readErr := sourceFile.Read(buffer)
		if count > 0 {
			if _, err := writer.Write(buffer[:count]); err != nil {
				_ = destinationFile.Close()
				return sum, true, fmt.Errorf("staging packaged app.jar: %w", err)
			}
		}
		if errors.Is(readErr, io.EOF) {
			break
		}
		if readErr != nil {
			_ = destinationFile.Close()
			return sum, true, fmt.Errorf("reading packaged app.jar: %w", readErr)
		}
	}
	if err := destinationFile.Sync(); err != nil {
		_ = destinationFile.Close()
		return sum, true, fmt.Errorf("syncing staged app.jar: %w", err)
	}
	if err := destinationFile.Close(); err != nil {
		return sum, true, fmt.Errorf("closing staged app.jar: %w", err)
	}
	copy(sum[:], hash.Sum(nil))
	return sum, true, nil
}

func (s *stagedContainerContext) cleanup() error {
	if s == nil {
		return nil
	}
	info, err := os.Lstat(s.directory)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("inspecting runtime context before cleanup: %w", err)
	}
	if !info.IsDir() || s.info == nil || !os.SameFile(info, s.info) {
		return validationError("spring_build_context_changed", "the runtime context directory changed during the build",
			"preserve unexpected changes in the temporary build context before removing it")
	}
	for path, expected := range map[string][sha256.Size]byte{
		s.jarPath: s.jarHash, s.recipePath: sha256.Sum256([]byte(springDockerfile)),
	} {
		info, err := os.Lstat(path)
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return fmt.Errorf("inspecting staged runtime file before cleanup: %w", err)
		}
		if !info.Mode().IsRegular() {
			return validationError("spring_build_context_changed", "a staged runtime file is no longer a regular file",
				"preserve unexpected changes in the temporary build context before removing it")
		}
		file, err := os.Open(path)
		if err != nil {
			return fmt.Errorf("verifying staged runtime file before cleanup: %w", err)
		}
		hash := sha256.New()
		_, hashErr := io.Copy(hash, file)
		if err := errors.Join(hashErr, file.Close()); err != nil {
			return fmt.Errorf("hashing staged runtime file before cleanup: %w", err)
		}
		if !bytes.Equal(hash.Sum(nil), expected[:]) {
			return validationError(
				"spring_build_context_changed",
				"a staged runtime file changed during the container build",
				"preserve unexpected changes in the temporary build context before removing it",
			)
		}
	}
	if err := errors.Join(removeContextFile(s.jarPath), removeContextFile(s.recipePath)); err != nil {
		return err
	}
	if err := os.Remove(s.directory); err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("removing Spring container build context: %w", err)
	}
	return nil
}

func removeContextFile(path string) error {
	if err := os.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("removing staged runtime file: %w", err)
	}
	return nil
}
