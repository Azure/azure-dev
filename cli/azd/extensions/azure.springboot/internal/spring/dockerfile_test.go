func createMavenProject(t *testing.T) (*azdext.ProjectConfig, *azdext.ServiceConfig) {
	t.Helper()
	root := t.TempDir()
	require.NoError(t, os.MkdirAll(filepath.Join(root, ".mvn", "wrapper"), 0o755))
	require.NoError(t, os.MkdirAll(filepath.Join(root, "src"), 0o755))
	for _, path := range []string{"pom.xml", "mvnw", filepath.Join(".mvn", "wrapper", "maven-wrapper.properties")} {
		require.NoError(t, os.WriteFile(filepath.Join(root, path), []byte("fixture"), 0o600))
	}
	require.NoError(t, os.WriteFile(filepath.Join(root, "pom.xml"), []byte(`<project><dependencies><dependency>
<groupId>com.h2database</groupId><artifactId>h2</artifactId><scope>runtime</scope>
</dependency></dependencies></project>`), 0o600))
	service := &azdext.ServiceConfig{Name: "petclinic", Host: SpringHost, RelativePath: "."}
	project := &azdext.ProjectConfig{
		Path:     root,
		Services: map[string]*azdext.ServiceConfig{"petclinic": service},
	}
	return project, service
}

func TestAuthoredDockerfilePreservesSourceAndIgnoresNativeMavenRequirements(t *testing.T) {
	project, service := createMavenProject(t)
	for _, path := range []string{"pom.xml", "mvnw", ".mvn", "src"} {
		require.NoError(t, os.RemoveAll(filepath.Join(project.Path, path)))
	}
	service.Docker = &azdext.DockerProjectOptions{Path: "Dockerfile", Context: ".", Platform: "linux/amd64"}
	recipe := []byte("FROM maven:3 AS build\nCOPY . .\nRUN mvn package\nEXPOSE 9966\n")
	ignore := []byte(".azd-springboot\n")
	require.NoError(t, os.WriteFile(filepath.Join(project.Path, "Dockerfile"), recipe, 0o600))
	require.NoError(t, os.WriteFile(filepath.Join(project.Path, ".dockerignore"), ignore, 0o600))
	require.NoError(t, prepareSpringBuild(project, service))
	got, err := os.ReadFile(filepath.Join(project.Path, "Dockerfile"))
	require.NoError(t, err)
	require.Equal(t, recipe, got)
	got, err = os.ReadFile(filepath.Join(project.Path, ".dockerignore"))
	require.NoError(t, err)
	require.Equal(t, ignore, got)
	require.NoDirExists(t, filepath.Join(project.Path, stagingDirectoryName))
	_, err = prepareContainerContext(t.Context(), project, service, nil)
	require.ErrorContains(t, err, "without JAR staging")
}

func TestAuthoredDockerfileRejectsInvalidInputsWithoutFallback(t *testing.T) {
	for _, test := range []struct {
		name   string
		docker *azdext.DockerProjectOptions
		recipe string
	}{
		{"missing", &azdext.DockerProjectOptions{Path: "missing"}, "FROM authored"},
		{"directory", &azdext.DockerProjectOptions{Path: "src"}, "FROM authored"},
		{"escape", &azdext.DockerProjectOptions{Path: "../Dockerfile"}, "FROM authored"},
		{"context escape", &azdext.DockerProjectOptions{Path: "Dockerfile", Context: ".."}, "FROM authored"},
		{"context file", &azdext.DockerProjectOptions{Path: "Dockerfile", Context: "pom.xml"}, "FROM authored"},
		{"generated", &azdext.DockerProjectOptions{Path: "Dockerfile"}, springDockerfile},
		{"legacy generated", &azdext.DockerProjectOptions{Path: "Dockerfile"},
			"# Generated by azure.springboot.\nFROM eclipse-temurin:17-jdk AS build\n"},
		{"target", &azdext.DockerProjectOptions{Path: "Dockerfile", Target: "builder"}, "FROM authored"},
		{"remote", &azdext.DockerProjectOptions{Path: "Dockerfile", RemoteBuild: true}, "FROM authored"},
		{"network", &azdext.DockerProjectOptions{Path: "Dockerfile", Network: "host"}, "FROM authored"},
		{"platform", &azdext.DockerProjectOptions{Path: "Dockerfile", Platform: "windows/amd64"}, "FROM authored"},
		{"build arguments", &azdext.DockerProjectOptions{Path: "Dockerfile", BuildArgs: []string{"X=Y"}}, "FROM authored"},
	} {
		t.Run(test.name, func(t *testing.T) {
			project, service := createMavenProject(t)
			service.Docker = test.docker
			path := filepath.Join(project.Path, "Dockerfile")
			require.NoError(t, os.WriteFile(path, []byte(test.recipe), 0o600))
			require.Error(t, prepareSpringBuild(project, service))
			content, err := os.ReadFile(path)
			require.NoError(t, err)
			require.Equal(t, test.recipe, string(content))
			require.NoDirExists(t, filepath.Join(project.Path, stagingDirectoryName))
		})
	}
}

func TestRawDockerSettingsRejectExplicitInvalidAndUnsupportedValues(t *testing.T) {
	for _, invalid := range []any{
		nil, "", []any{},
		map[string]any{"path": nil},
		map[string]any{"path": ""},
		map[string]any{"path": " "},
		map[string]any{"path": true},
		map[string]any{"context": nil},
		map[string]any{"target": ""},
		map[string]any{"buildArgs": []any{}},
		map[string]any{"remoteBuild": true},
		map[string]any{"unknown": "value"},
	} {
		require.Error(t, validateRawDockerSettings(map[string]any{"docker": invalid}))
	}
	require.NoError(t, validateRawDockerSettings(nil))
	require.NoError(t, validateRawDockerSettings(map[string]any{"docker": map[string]any{
		"path": "Dockerfile", "context": ".", "platform": "linux/amd64", "remoteBuild": false,
	}}))
}

