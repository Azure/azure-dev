func restoreSpringImages(t *testing.T, ctx context.Context, before map[string]string) {
	t.Helper()
	cleanupCtx, cancel := context.WithTimeout(ctx, 2*time.Minute)
	defer cancel()
	after := springImageSnapshot(t, cleanupCtx)
	newImageIDs := map[string]bool{}
	for reference, imageID := range after {
		previousID, existed := before[reference]
		switch {
		case !existed:
			newImageIDs[imageID] = true
			output, err := osexec.CommandContext(
				cleanupCtx, "docker", "image", "rm", reference,
			).CombinedOutput()
			if err != nil {
				t.Errorf("removing test image %s: %v: %s", reference, err, output)
			}
		case previousID != imageID:
			newImageIDs[imageID] = true
			output, err := osexec.CommandContext(
				cleanupCtx, "docker", "tag", previousID, reference,
			).CombinedOutput()
			if err != nil {
				t.Errorf("restoring pre-existing image %s: %v: %s", reference, err, output)
			}
		}
	}
	for imageID := range newImageIDs {
		_, _ = osexec.CommandContext(cleanupCtx, "docker", "image", "rm", imageID).CombinedOutput()
	}
}

func verifyH2ContainerStartup(t *testing.T, ctx context.Context, image string) {
	t.Helper()
	name := "azd-springboot-h2-" + strconv.FormatInt(time.Now().UnixNano(), 10)
	run := osexec.CommandContext(
		ctx,
		"docker",
		"run",
		"--detach",
		"--name",
		name,
		"--publish",
		"127.0.0.1::8080",
		image,
	)
	output, err := run.CombinedOutput()
	require.NoError(t, err, "starting packaged H2 container: %s", output)
	containerID := strings.TrimSpace(string(output))
	require.NotEmpty(t, containerID)
	t.Cleanup(func() {
		cleanupCtx, cancel := context.WithTimeout(context.Background(), time.Minute)
		defer cancel()
		_, _ = osexec.CommandContext(cleanupCtx, "docker", "rm", "--force", containerID).CombinedOutput()
	})

	portCommand := osexec.CommandContext(ctx, "docker", "port", containerID, "8080/tcp")
	output, err = portCommand.CombinedOutput()
	require.NoError(t, err, "reading H2 container port: %s", output)
	address := strings.TrimSpace(string(output))
	require.NotEmpty(t, address)
	if after, ok := strings.CutPrefix(address, "0.0.0.0:"); ok {
		address = "127.0.0.1:" + after
	}
	endpoint := "http://" + address + "/actuator/health"

	client := &http.Client{Timeout: 5 * time.Second}
	deadline := time.Now().Add(4 * time.Minute)
	var lastResponse string
	for time.Now().Before(deadline) {
		request, requestErr := http.NewRequestWithContext(ctx, http.MethodGet, endpoint, nil)
		if requestErr != nil {
			require.NoError(t, requestErr)
		}
		response, requestErr := client.Do(request)
		if requestErr == nil {
			body, readErr := io.ReadAll(response.Body)
			_ = response.Body.Close()
			if readErr == nil {
				lastResponse = string(body)
				if response.StatusCode == http.StatusOK && strings.Contains(lastResponse, `"status":"UP"`) {
					return
				}
			}
		}
		select {
		case <-ctx.Done():
			require.NoError(t, ctx.Err())
		case <-time.After(2 * time.Second):
		}
	}
	logs, _ := osexec.CommandContext(ctx, "docker", "logs", containerID).CombinedOutput()
	t.Fatalf("packaged H2 container did not become healthy; last response %q; logs:\n%s", lastResponse, logs)
}

