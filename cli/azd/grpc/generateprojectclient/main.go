// generateprojectclient snapshots canonical beta descriptors for released-SDK consumers.
package main

import (
	"bytes"
	"encoding/base64"
	"flag"
	"fmt"
	"go/format"
	"os"
	"slices"

	v1beta "github.com/azure/azure-dev/cli/azd/pkg/azdext/contracts/v1beta"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protodesc"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
)

func main() {
	output := flag.String("output", "", "generated descriptor Go file")
	flag.Parse()
	if err := generate(*output); err != nil {
		fmt.Fprintf(os.Stderr, "generate project client: %v\n", err)
		os.Exit(1)
	}
}

func generate(output string) error {
	if output == "" {
		return fmt.Errorf("-output is required")
	}
	set := &descriptorpb.FileDescriptorSet{}
	seen := map[string]bool{}
	var visit func(protoreflect.FileDescriptor)
	visit = func(file protoreflect.FileDescriptor) {
		if seen[file.Path()] {
			return
		}
		seen[file.Path()] = true
		for i := range file.Imports().Len() {
			visit(file.Imports().Get(i).FileDescriptor)
		}
		set.File = append(set.File, protodesc.ToFileDescriptorProto(file))
	}
	visit(v1beta.File_azd_extensions_v1beta_project_proto)
	slices.SortFunc(set.File, func(a, b *descriptorpb.FileDescriptorProto) int {
		return bytes.Compare([]byte(a.GetName()), []byte(b.GetName()))
	})
	wire, err := proto.MarshalOptions{Deterministic: true}.Marshal(set)
	if err != nil {
		return err
	}
	source := fmt.Sprintf(`// Copyright (c) Microsoft Corporation. All rights reserved.
// Licensed under the MIT License.

// Code generated by grpc/generateprojectclient from canonical v1beta descriptors. DO NOT EDIT.
// cspell:disable

package hostproject

const descriptorSetBase64 = %q
const addServiceMethod = %q
const capabilitiesMethod = %q
`, base64.StdEncoding.EncodeToString(wire),
		v1beta.ProjectService_AddService_FullMethodName,
		v1beta.ProjectService_GetAddServiceCapabilities_FullMethodName)
	formatted, err := format.Source([]byte(source))
	if err != nil {
		return err
	}
	return os.WriteFile(output, formatted, 0o644) //nolint:gosec // Repository-readable generated source.
}
