package helpformat

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

func TestGeneratedExtensionFormatters(t *testing.T) {
	source, err := os.ReadFile("helpformat.go")
	require.NoError(t, err)
	modules, err := filepath.Glob(filepath.Join("..", "..", "extensions", "azure.ai.*", "go.mod"))
	require.NoError(t, err)
	require.NotEmpty(t, modules)
	for _, module := range modules {
		t.Run(filepath.Base(filepath.Dir(module)), func(t *testing.T) {
			generated, err := os.ReadFile(filepath.Join(filepath.Dir(module), "internal", "helpformat", "helpformat.go"))
			require.NoError(t, err, "run go generate ./internal/helpformat from cli/azd")
			require.Equal(t,
				strings.Replace(string(source), "\n\n",
					"\n\n// Code generated by go generate ./internal/helpformat from cli/azd; DO NOT EDIT.\n\n", 1),
				string(generated), "run go generate ./internal/helpformat from cli/azd")
		})
	}
}
