// Command generate keeps independently released AI extensions on the same help
// renderer without requiring an unreleased azd SDK or local module replacements.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	source, err := os.ReadFile("helpformat.go")
	if err != nil {
		return fmt.Errorf("reading canonical help formatter: %w", err)
	}
	modules, err := filepath.Glob(filepath.Join("..", "..", "extensions", "azure.ai.*", "go.mod"))
	if err != nil {
		return fmt.Errorf("finding AI extension modules: %w", err)
	}
	if len(modules) == 0 {
		return fmt.Errorf("no AI extension modules found; run go generate from internal/helpformat")
	}
	generated := strings.Replace(string(source), "\n\n",
		"\n\n// Code generated by go generate ./internal/helpformat from cli/azd; DO NOT EDIT.\n\n", 1)
	for _, module := range modules {
		root := filepath.Dir(module)
		manifest, err := os.ReadFile(filepath.Join(root, "extension.yaml"))
		if err != nil {
			return fmt.Errorf("reading manifest for %s: %w", root, err)
		}
		if !strings.Contains(string(manifest), "\nnamespace: ai.") {
			return fmt.Errorf("%s is not an AI command extension", root)
		}
		dir := filepath.Join(root, "internal", "helpformat")
		if err := os.MkdirAll(dir, 0755); err != nil {
			return fmt.Errorf("creating formatter directory: %w", err)
		}
		// #nosec G703 -- Paths come from the fixed repository module glob, not user input.
		if err := os.WriteFile(filepath.Join(dir, "helpformat.go"), []byte(generated), 0600); err != nil {
			return fmt.Errorf("writing formatter for %s: %w", root, err)
		}
	}
	return nil
}
